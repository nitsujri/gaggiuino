#!/usr/bin/env python3
"""Rasterize actual Nextion commands. Font substitutes are labelled explicitly."""
import csv,re
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path('tmp/indigo-native-preview')
fontpath='/System/Library/Fonts/Supplemental/Arial.ttf'
fonts={i:ImageFont.truetype(fontpath,size) for i,size in [(0,12),(1,24),(6,40)]}
def color(n):
 n=int(n);r=(n>>11)&31;g=(n>>5)&63;b=n&31
 return(r<<3|r>>2,g<<2|g>>4,b<<3|b>>2)
previous=None
for path in root.glob('*.txt'):
 if path.name=='README.txt':continue
 image=Image.open(root/'manual.png').copy() if path.stem=='manual-live' else Image.new('RGB',(320,240),color(0x10e6));d=ImageDraw.Draw(image)
 for line in path.read_text().splitlines():
  op,_,args=line.partition(' ')
  if op=='vis' and args=='h0,1':
   d.rectangle((15,181,302,220),fill=color(0x21aa));d.line((25,201,292,201),fill=color(0x42ef),width=5);d.ellipse((16,187,42,215),fill=color(0x9d7f));continue
  if op not in ['fill','cirs','cir','xstr','line']:continue
  values=next(csv.reader([args],skipinitialspace=True))
  if op=='fill':
   x,y,w,h,c=map(int,values);d.rectangle((x,y,x+w-1,y+h-1),fill=color(c))
  elif op=='line':
   x,y,x2,y2,c=map(int,values);d.line((x,y,x2,y2),fill=color(c))
  elif op in ['cir','cirs']:
   x,y,r,c=map(int,values);d.ellipse((x-r,y-r,x+r,y+r),**({'fill':color(c)} if op=='cirs' else {'outline':color(c)}))
  else:
   x,y,w,h,font,fg,bg,xa,ya,sta=map(int,values[:10]);s=values[10];face=fonts.get(font,fonts[0]);width=d.textlength(s,font=face);box=d.textbbox((0,0),s,font=face);height=box[3]-box[1]
   patch=Image.new('RGB',(w,h),color(bg));p=ImageDraw.Draw(patch);tx=0 if xa==0 else(w-width)/2 if xa==1 else w-width;ty=(h-height)/2-box[1]
   p.text((tx,ty),s,font=face,fill=color(fg));image.paste(patch,(x,y))
 image.save(path.with_suffix('.png'))
images=sorted(p for p in root.glob('*.png') if p.name!='contact-sheet.png');tile=Image.new('RGB',(3*340,((len(images)+2)//3)*280),(235,235,235));draw=ImageDraw.Draw(tile)
for i,p in enumerate(images):x=i%3*340;y=i//3*280;tile.paste(Image.open(p),(x+10,y+25));draw.text((x+10,y+5),p.stem,fill='black')
tile.save(root/'contact-sheet.png')
(root/'README.txt').write_text('Generated by production C++ renderer, using actual native drawing commands. The rasterizer substitutes Arial for the display ZI fonts; glyph widths and physical touch still require on-screen verification. These PNGs are not flashable TFT files.\n')
